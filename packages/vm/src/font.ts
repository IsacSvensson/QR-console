/** Glyph bits for a character code, or null if the font has no glyph (drawn as blank). */
export function glyph(code: number): number | null {
  if (code >= 97 && code <= 122) code -= 32;
  if (code < 32 || code > 95) return null;
  return FONT[code - 32]!;
}
