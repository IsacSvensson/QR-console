// The M27 mockup (PLAN.md Part 5): fixed views of rooms 1.1 (GATE) and 2.1 (OPEN OFFICE) rendered by the real
// engine, measured: cycles per image, frames per image, and the share of the low-cell pass (DECISIONS D-041).
// Writes ../mockup/<room>-<n>.png and ../mockup/MOCKUP.md. Run: npx tsx games/blackbox3d/tools/mockup.ts
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { writeFramePng } from '../../../packages/tools/src/png';
import { buildBb3d, startVM } from './game';
import { GAME_DIR } from './util';

interface View {
  room: string;
  x: number; // cell, centre of the player
  y: number;
  ang: number; // 0..1023
  note: string;
}

const VIEWS: View[] = [
  { room: '1_1', x: 1.5, y: 12.5, ang: 896, note: 'arrival, towards the guard behind the desks' },
  { room: '1_1', x: 7.5, y: 11.5, ang: 768, note: 'between the desk rows, facing north (shelves)' },
  { room: '2_1', x: 7.5, y: 13.0, ang: 768, note: 'south door, the whole office ahead (many desks)' },
  { room: '2_1', x: 4.5, y: 8.5, ang: 0, note: 'between desk blocks, facing east along a row' },
];

const LOW = new Set(['draw_low', 'low_rec']);
const dir = join(GAME_DIR, 'mockup');
mkdirSync(dir, { recursive: true });
const b = await buildBb3d();
const labels = [...b.asm.symbols.entries()].filter(([n, v]) => /^[a-z]\w*$/.test(n) && v < b.cart.sections.code.length).sort((p, q) => p[1] - q[1]);
const of = new Map<number, string>();
for (let pc = 0, i = 0; pc < b.cart.sections.code.length; pc += 4) {
  while (i + 1 < labels.length && labels[i + 1]![1] <= pc) i++;
  of.set(pc, labels[i]![0]);
}

const rows: string[] = [];
for (const [k, v] of VIEWS.entries()) {
  const vm = startVM(b, 1, 10_000_000);
  vm.step(0);
  vm.write16(b.sym('dbg_room'), b.sym(`R_${v.room}`) + 1);
  vm.step(0); // loads the room (no rays in that frame)
  // stand still for the guard; put the player at the view
  vm.write16(b.sym('px'), Math.round(v.x * 8) - 4);
  vm.write16(b.sym('py'), Math.round(v.y * 8) - 4);
  vm.write16(b.sym('ang'), v.ang);
  vm.write16(b.sym('mode'), b.sym('M_PLAY'));
  vm.write16(b.sym('script_pc'), 0); // the room's ENTER dialogue (if any) is not part of the view
  // run until two images have been presented; measure the second
  let low = 0;
  let total = 0;
  let frames = 0;
  let max = 0;
  const startImages = () => vm.read16(b.sym('images'));
  const i0 = startImages();
  while (startImages() < i0 + 1) vm.step(0);
  vm.tracer = (pc) => {
    const g = of.get(pc) ?? '';
    if (LOW.has(g)) low += vm.read8(pc) === 0x20 ? 8 : 1;
  };
  while (startImages() < i0 + 2) {
    vm.step(0);
    frames++;
    total += vm.cyclesLastFrame;
    max = Math.max(max, vm.cyclesLastFrame);
  }
  vm.tracer = null;
  const png = `${v.room.replace('_', '.')}-${k + 1}.png`;
  writeFramePng(join(dir, png), vm.fb, 3);
  rows.push(`| ${png} | ${v.room.replace('_', '.')} | ${v.note} | ${total} | ${frames} | ${max} | ${((100 * low) / total).toFixed(0)} % |`);
  console.log(rows[rows.length - 1]);
}

writeFileSync(
  join(dir, 'MOCKUP.md'),
  [
    '# BLACKBOX 3D mockup (M27)',
    '',
    '_Generated by `npx tsx games/blackbox3d/tools/mockup.ts`: the real engine, fixed views, headless VM. Cycles are the',
    "VM's own count for one whole image (the frames from its first ray to its presentation, including the game logic of",
    'those frames). *Low pass* is the share spent drawing desks, terminals and other low cells (DECISIONS D-041)._',
    '',
    '| Picture | Room | View | Cycles per image | Frames per image | Max cycles in a frame | Low pass |',
    '|---|---|---|---:|---:|---:|---:|',
    ...rows,
    '',
  ].join('\n'),
);
