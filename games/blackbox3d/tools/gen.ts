// Writes BLACKBOX 3D's generated sources (npm run bb3d:gen):
//   rooms.gen.asm, text.gen.asm  exactly BLACKBOX's (games/blackbox/tools/gen.ts, text.ts): same rooms, same text
//   tables.gen.asm               the 3D tables, textures and actor pictures (DESIGN.md §3-4)
//   duff.gen.asm                 the unrolled column writer for the 88-row view
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { generate as generateRooms, TILE_NAMES } from '../../blackbox/tools/gen';
import { generateText } from '../../blackbox/tools/text';
import { camOf, generateDuff, spriteSizeFor, tilesOf, wallRows } from '../../fps/tools/tables';
import { ACTOR_ART, ACTOR_PICS, DARK, FIRST_LOW, LOW_ROW, SETS, SPRITE_SIZES, TEX_NAMES, ZONE_SET, lowTop, texturePixels } from './art';
import { GAME_DIR, isMain } from './util';

// ---- numbers shared with the engine (DESIGN.md §3) ----------------------------------------------------
export const ANGLES = 1024;
export const ONE = 256;
export const FOCAL = 97;
export const PLANE = 169;
export const VIEW_W = 128;
export const VIEW_H = 88;
export const NRAYS = 64;
export const PERP_MIN = 64;
/** walls are two cells high (DESIGN.md §3.2): a BLACKBOX tile is about a person's width */
export const WALL_SCALE = 2;
/** q = FOCAL * 256 / distance; the wall is h = 2q pixels high. QMAX at the nearest distance drawn. */
export const QMAX = Math.floor((FOCAL * ONE) / PERP_MIN);
export const RECIP_N = 512;
export const RECIP_MAX = 32767;

/** render code of each room tile code (DESIGN.md §3.1): 0 empty, 1..7 full wall texture, 0x80 | t low cell */
export const RENDER_OF: Record<string, number> = {
  FLOOR: 0, WALL: 1, WALLFACE: 1, SHELF: 2, CAMERA: 3, DESK: 0x80 | 8, DOOR: 0, LOCKED: 4, VENT: 5, TERMINAL: 0x80 | 9, CHARGER: 0x80 | 10, LIFT: 6, CABLE: 0x80 | 11,
};
/** a doorway or vent on the room's border is drawn as a portal (texture 7) */
export const PORTAL = 7;

const words = (label: string, v: (string | number)[], per = 16) => {
  const out = [`${label}:`];
  for (let i = 0; i < v.length; i += per) out.push(`    .word ${v.slice(i, i + per).join(', ')}`);
  return out.join('\n');
};
const bytes = (label: string, v: number[], per = 32) => {
  const out = label ? [`${label}:`] : [];
  for (let i = 0; i < v.length; i += per) out.push(`    .byte ${v.slice(i, i + per).join(', ')}`);
  return out.join('\n');
};

/** A 16x16 actor picture scaled to s x s by nearest neighbour (as the FPS spike). */
export function scaledPic(name: string, s: number): number[] {
  const rows = ACTOR_ART[name]!;
  if (rows.length !== 16 || rows.some((r) => r.length !== 16)) throw new Error(`picture ${name} must be 16x16`);
  const out: number[] = [];
  for (let y = 0; y < s; y++) for (let x = 0; x < s; x++) {
    const ch = rows[Math.floor((y * 16) / s)]![Math.floor((x * 16) / s)]!;
    out.push(ch === '.' ? 0 : parseInt(ch, 16));
  }
  return out;
}

/** BLACKBOX's attribute constants and table, taken from its generated tiles file so both games agree */
function blackboxAttrs(): string[] {
  const src = readFileSync(join(GAME_DIR, '../blackbox/tiles.gen.asm'), 'utf8');
  const consts = src.split('\n').filter((l) => /^A_\w+ = \d+$/.test(l));
  const attr = /tile_attr:\n(\s+\.byte [^\n]+)/.exec(src)![1]!;
  return [...consts, '.data', 'tile_attr:', attr];
}

export function generateTables(): string {
  const L: string[] = [
    '; generated by games/blackbox3d/tools/gen.ts (npm run bb3d:gen) - do not edit',
    `QMAX = ${QMAX}`, `WALL_SCALE = ${WALL_SCALE}`, `PERP_MIN = ${PERP_MIN}`, `FOCAL = ${FOCAL}`, `FOCAL256 = ${FOCAL * ONE}`, `PLANE = ${PLANE}`,
    `VIEW_H = ${VIEW_H}`, `NRAYS = ${NRAYS}`, `RAYS_PER_TC = 4`, `COLW = 2`, `COLW_SHIFT = 1`,
    `NUM_SIZES = ${SPRITE_SIZES.length}`, `MAX_SIZE = ${SPRITE_SIZES[SPRITE_SIZES.length - 1]}`,
    `FIRST_LOW = ${FIRST_LOW}`, `LOW_ROW = ${LOW_ROW}`, `NUM_TEX = ${TEX_NAMES.length + 1}`, `R_PORTAL = ${PORTAL}`, `R_LOW = 0x80`,
    ...ACTOR_PICS.map((p, i) => `PIC_${p.toUpperCase()} = ${i}`),
  ];
  const runBytes: number[] = [];
  for (let q = 1; q <= QMAX; q++) {
    const { y0, runs } = wallRows(WALL_SCALE * q, VIEW_H);
    runBytes.push(y0, runs.length, ...runs.flat());
  }
  const picBytes: number[] = [];
  const picTable: string[] = [];
  for (const pic of ACTOR_PICS)
    for (const s of SPRITE_SIZES) {
      picTable.push(`spr_ram + ${picBytes.length}`, String(s / 8));
      picBytes.push(...tilesOf(scaledPic(pic, s), s, s, 'cols'));
    }
  L.push(`RUNS_BYTES = ${runBytes.length}`, `SPR_BYTES = ${picBytes.length}`, '', ...blackboxAttrs());

  L.push('; render code of each room tile (T_* order)', bytes('rclass', TILE_NAMES.map((n) => RENDER_OF[n]!)));
  L.push('; per tileset: ceiling and floor colour bytes (both pixels), and the top colour of each low texture');
  L.push(bytes('set_ceil', SETS.map((s) => s.ceil * 17)), bytes('set_floor', SETS.map((s) => s.floor * 17)));
  L.push(bytes('low_top', SETS.flatMap((_, set) => TEX_NAMES.slice(FIRST_LOW - 1).map((n) => lowTop(n, set) * 17))));
  L.push(bytes('zone_set', ZONE_SET));
  const sin = Array.from({ length: ANGLES / 4 + 1 }, (_, i) => Math.round(Math.sin((2 * Math.PI * i) / ANGLES) * ONE));
  L.push('; sin of angle i = 0..256 (a quarter turn; 1024 = full turn) in 8.8: sin_of mirrors it', words('sinq', sin));
  const recip = Array.from({ length: RECIP_N }, (_, i) => (i === 0 ? RECIP_MAX : Math.min(RECIP_MAX, Math.round((ONE * ONE) / i))));
  L.push('; |1 / x| in 8.8 for an 8.8 ray component x = 0..511, capped at 128 cells', words('recip_t', recip));
  L.push(words('cam_64', Array.from({ length: NRAYS }, (_, c) => camOf(NRAYS, c))));
  const rowsT = VIEW_H / 8;
  L.push(words('colb_64', Array.from({ length: NRAYS }, (_, c) => `buf + ${(c >> 2) * rowsT * 32 + (c & 3)}`), 8));
  const view: number[] = [];
  for (let ty = 0; ty < rowsT; ty++) for (let tx = 0; tx < 16; tx++) view.push(1 + tx * rowsT + ty);
  L.push(`; the view as a 16x${rowsT} tilemap over the RAM buffer (tiles = buf - 32)`, bytes('view_map', view, 16));
  L.push('; picture size index for each q (wall height 2q; 255 = too small)', bytes('spr_size', Array.from({ length: QMAX + 1 }, (_, q) => (q === 0 ? 255 : spriteSizeFor(WALL_SCALE * q, SPRITE_SIZES)))));
  L.push(`size_px: .word ${SPRITE_SIZES.join(', ')}`);
  L.push(`; per picture (${ACTOR_PICS.join(', ')}), per size: tiles (column order), tiles per side`, words('pic_table', picTable, 4));

  // textures: far addresses per tileset, render texture (0..11) and side
  const texFar: string[] = [];
  const texData: string[] = [];
  SETS.forEach((set, si) => {
    texFar.push('0, 0, 0, 0');
    TEX_NAMES.forEach((name) => {
      const px = texturePixels(name, si);
      for (const dark of [0, 1]) {
        const lbl = `tex_${set.name}_${name}_${dark}`;
        texFar.push(`${lbl} >> 16, ${lbl} & 0xFFFF`);
        const col: number[] = [];
        for (let u = 0; u < 16; u++) for (let v = 0; v < 16; v++) col.push((dark ? DARK[px[v * 16 + u]!]! : px[v * 16 + u]!) * 17);
        texData.push(bytes(lbl, col, 16));
      }
    });
  });
  L.push('; per tileset, per render texture 0..11, per side (x, y): far address of its column-major texels', words('tex_far', texFar, 4));
  L.push('', '.xdata', 'runs_x:', '.pack', bytes('', runBytes), '.endpack', 'spr_x:', '.pack', bytes('', picBytes), '.endpack', ...texData, '');
  return L.join('\n');
}

export const GENERATED: Record<string, () => string> = {
  'rooms.gen.asm': generateRooms,
  'text.gen.asm': () => generateText(),
  'tables.gen.asm': generateTables,
  'duff.gen.asm': () => generateDuff(2, VIEW_H, 'games/blackbox3d/tools/gen.ts (npm run bb3d:gen)'),
};

if (isMain(import.meta.url)) {
  for (const [file, gen] of Object.entries(GENERATED)) {
    const out = gen();
    writeFileSync(join(GAME_DIR, file), out);
    console.log(`${file}: ${out.length} chars`);
  }
}
