// npm run bench:bb3d — measures BLACKBOX 3D (PLAN.md M28) and writes bench/bb3d.md:
//  1. the slice: images per second and cycles per image in each room, on the inputs of the recorded replays;
//  2. all 37 rooms (the budget gate): a full turn on the floor cell nearest each room's middle, cycles per frame
//     and frames per image;
//  3. sizes: ROM, xdata, RAM, cartridge, QR loop, and what the remaining sections still need.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DEFAULT_QR, blockSizeFor, defaultFrameCount } from '@qrc/qr';
import { blockCount } from '@qrc/transport';
import { expandInputs, type ReplayFile } from '@qrc/vm';
import { parseLayout } from '../../blackbox/tools/layout';
import { buildBb3d, startVM } from './game';
import { GAME_DIR } from './util';

const REPO = join(GAME_DIR, '../..');
const k = (v: number) => Math.round(v).toLocaleString('en-US').replace(/,/g, ' ');
const b = await buildBb3d();
const rooms = parseLayout();
const out: string[] = [
  '# BLACKBOX 3D benchmark (M28)',
  '',
  "_Generated by `npm run bench:bb3d` (games/blackbox3d/tools/bench.ts). Headless VM, the VM's own cycle count;",
  'nothing here is a measurement on a device._',
  '',
  '## 1. The slice, room by room',
  '',
  'All frames of the recorded replays (slice, tour, caught) spent in each room in free play.',
  '',
  '| Room | Frames | Images | Images per second | Mean cycles per frame | Max cycles per frame |',
  '|---|---:|---:|---:|---:|---:|',
];

const per = new Map<string, { frames: number; images: number; sum: number; max: number }>();
for (const name of ['slice', 'tour', 'caught']) {
  const rf = JSON.parse(readFileSync(join(GAME_DIR, 'replays', `${name}.json`), 'utf8')) as ReplayFile & { frames: number };
  const vm = startVM(b, rf.seed ?? 1);
  const inputs = expandInputs(rf.inputs, rf.frames);
  for (const i of inputs) {
    const images = vm.read16(b.sym('images'));
    vm.step(i);
    if (vm.read16(b.sym('mode')) !== b.sym('M_PLAY')) continue;
    const id = rooms[vm.read16(b.sym('room'))]!.id;
    const p = per.get(id) ?? { frames: 0, images: 0, sum: 0, max: 0 };
    p.frames++;
    p.images += vm.read16(b.sym('images')) !== images ? 1 : 0;
    p.sum += vm.cyclesLastFrame;
    p.max = Math.max(p.max, vm.cyclesLastFrame);
    per.set(id, p);
  }
}
for (const [id, p] of [...per.entries()].sort()) out.push(`| ${id} | ${p.frames} | ${p.images} | ${((60 * p.images) / p.frames).toFixed(1)} | ${k(p.sum / p.frames)} | ${k(p.max)} |`);

out.push(
  '',
  '## 2. All 37 rooms: a full turn (the budget gate)',
  '',
  "Each room loaded on its own (test hook), the player on the floor cell nearest the room's middle, turning right for",
  '128 frames (one full turn) with the actors moving. *Frames per image* = frames / images in that turn.',
  '',
  '| Room | Name | Cell | Images per second | Frames per image | Max cycles per frame |',
  '|---|---|---|---:|---:|---:|',
);
let worst = 0;
let slowest = Infinity;
for (const [i, r] of rooms.entries()) {
  const vm = startVM(b, 1);
  vm.step(0);
  vm.write16(b.sym('dbg_room'), i + 1);
  vm.step(0);
  // the floor cell nearest the middle (7.5, 7)
  let best: [number, number] = [7, 7];
  let bd = Infinity;
  r.grid.forEach((row, y) => [...row].forEach((ch, x) => {
    const d = (x - 7.5) ** 2 + (y - 7) ** 2;
    if ('.gdhupanbi@'.includes(ch) && d < bd) {
      bd = d;
      best = [x, y];
    }
  }));
  vm.write16(b.sym('px'), best[0] * 8);
  vm.write16(b.sym('py'), best[1] * 8);
  vm.write16(b.sym('mode'), b.sym('M_PLAY'));
  vm.write16(b.sym('script_pc'), 0);
  vm.write16(b.sym('grace_t'), 10_000); // a turn, not a stealth test
  for (let f = 0; f < 8; f++) vm.step(0);
  const i0 = vm.read16(b.sym('images'));
  let max = 0;
  for (let f = 0; f < 128; f++) {
    vm.step(2); // RIGHT
    if (vm.fault) throw new Error(`${r.id}: ${vm.fault}`);
    max = Math.max(max, vm.cyclesLastFrame);
  }
  const images = vm.read16(b.sym('images')) - i0;
  worst = Math.max(worst, max);
  slowest = Math.min(slowest, (60 * images) / 128);
  out.push(`| ${r.id} | ${r.name} | ${best.join(',')} | ${((60 * images) / 128).toFixed(1)} | ${(128 / images).toFixed(2)} | ${k(max)} |`);
}
out.push('', `Worst frame in all 37 rooms: **${k(worst)} cycles** (budget 50 000, ceiling 25 000). Slowest room: **${slowest.toFixed(1)} images per second**.`);

const s = b.cart.sections;
const rom = s.code.length + s.rodata.length + s.sound.length;
const ramEnd = b.sym('spr_ram') + b.sym('SPR_BYTES');
const K = blockCount(b.bytes.length, blockSizeFor(DEFAULT_QR.version, DEFAULT_QR.ecc));
out.push(
  '',
  '## 3. Sizes and what the rest of the game needs',
  '',
  '| Metric | Value |',
  '|---|---|',
  `| ROM | ${k(rom)} B of 32 768 (code ${k(s.code.length)}, data ${k(s.rodata.length)}); free ${k(32768 - rom)} B |`,
  `| xdata | ${k(s.xdata?.length ?? 0)} B (textures 22 528 B unpacked; run lists and pictures packed) |`,
  `| RAM | ${k(ramEnd - 0x8000)} B of 32 768 used by variables; free ${k(0x10000 - ramEnd)} B (stack included) |`,
  `| Cartridge | ${k(b.bytes.length)} B (ISA ${b.cart.header.isaVersion}) |`,
  `| As QR (v${DEFAULT_QR.version}-${DEFAULT_QR.ecc}, 150 ms) | K = ${K} blocks, ${defaultFrameCount(K)} frames per loop (${((defaultFrameCount(K) * 150) / 1000).toFixed(1)} s) |`,
  '',
  "**Projection for all 37 rooms.** Every room's logic, scripts and text are already in ROM (BLACKBOX's own modules):",
  "the slice's ROM is the whole game's ROM except what M29-M31 add.",
  '',
  '- **Pictures.** NPCs, drone, hunter, prototype, agent and the two bosses take about 2 KB of xdata per picture packed',
  '  (5 sizes). In RAM, pictures would be unpacked per room: the slice holds 4 pictures (8.4 KB), and the free RAM',
  '  allows about 3 more at a time.',
  '- **Code.** Per-room picture loading and boss billboards are estimated at 0.5-1 KB, against the free ROM in the',
  '  table above.',
  '- **Cycles.** Section 2 above shows every room within the ceiling already.',
  '',
);
writeFileSync(join(REPO, 'bench/bb3d.md'), out.join('\n'));
console.log(out.join('\n'));
