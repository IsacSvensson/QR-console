// Writes floor.gen.asm (DESIGN.md §3.7): one 16-byte record per 1/1024 turn of the camera with everything about
// the floor seams that depends only on the view angle, so a frame fetches its record with one COPY from xdata
// (8 + 2 cycles) and draws every seam with additions:
//   radial seams (the grid lines most along the view): x(y) = XV - step(y) * d, d = line - camera in cells,
//     step at the bottom row FL_YB and at the far row FL_YF (1/16 px per cell, signs folded in);
//   crossing seams (the other family): y(x) = horizon + PP / d at x = 0 and x = 127 (PP * 256, d in u8.8).
// Run: npx tsx games/nadir/tools/floorgen.ts   (or npm run nadir:gen)
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { k } from './design';
import { GAME_DIR, isMain, wordLines } from './util';

export const FL_YB = 127; // bottom row of the radial seams
export const FL_YF = 74; // far row: the seams fade out about 5 cells away
export const FLOOR_RECS = 1024;

export interface FloorRec {
  /** 0: radial seams are the x = k lines (view mostly along y); 1: the y = k lines */
  radialY: number;
  xv16: number;
  sb16: number;
  sf16: number;
  pp0: number;
  pp1: number;
}

export function floorRec(a: number): FloorRec {
  const th = ((a * 4 + 2) * 2 * Math.PI) / k('ANGLES');
  const s = Math.sin(th);
  const c = Math.cos(th);
  const F = k('F256') / 256;
  const H = k('HORIZON');
  const gb = 2 * (FL_YB + 0.5 - H);
  const gf = 2 * (FL_YF + 0.5 - H);
  const r16 = (v: number) => Math.max(-32767, Math.min(32767, Math.round(v * 16)));
  if (Math.abs(s) >= Math.abs(c)) {
    return { radialY: 0, xv16: r16(64 + (F * c) / s), sb16: r16(gb / s), sf16: r16(gf / s), pp0: Math.round(((F * s + 64 * c) / 2) * 256), pp1: Math.round(((F * s - 63 * c) / 2) * 256) };
  }
  return { radialY: 1, xv16: r16(64 - (F * s) / c), sb16: r16(-gb / c), sf16: r16(-gf / c), pp0: Math.round(((F * c + 64 * s) / 2) * 256), pp1: Math.round(((F * c - 63 * s) / 2) * 256) };
}

export function floorAsm(): string {
  const recs = Array.from({ length: FLOOR_RECS }, (_, a) => floorRec(a));
  return [
    '; GENERATED by games/nadir/tools/floorgen.ts from DESIGN.md §3.7 - do not edit.',
    `FL_YB = ${FL_YB}`,
    `FL_YF = ${FL_YF}`,
    '',
    '.xdata',
    '; per camera angle >> 2: radialY, XV16, SB16, SF16, PP0, PP1, 0, 0',
    'floor_x:',
    ...recs.flatMap((r) => wordLines([r.radialY, r.xv16 & 0xffff, r.sb16 & 0xffff, r.sf16 & 0xffff, r.pp0 & 0xffff, r.pp1 & 0xffff, 0, 0])),
    '',
  ].join('\n');
}

if (isMain(import.meta.url)) {
  writeFileSync(join(GAME_DIR, 'floor.gen.asm'), floorAsm());
  console.log('floor.gen.asm written');
}
