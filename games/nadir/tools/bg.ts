// Writes bg.gen.asm (DESIGN.md §3.7): per zone 17 floor/ceiling tiles, one per row of the 16 x 17 background map
// drawn at y = bob - 8. Each tile row is a Bayer-dithered step of the zone's floor or ceiling colour through the
// shade table at the fog level of that screen row's floor distance, so floor and ceiling darken exactly like the
// walls. Colour 0 is left transparent: the frame starts with CLS 0, so the far band near the horizon is black.
// Run: npx tsx games/nadir/tools/bg.ts   (or npm run nadir:gen)
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ZONES, k } from './design';
import { GAME_DIR, byteLines, isMain } from './util';

const BAYER = [
  [0, 8, 2, 10],
  [12, 4, 14, 6],
  [3, 11, 1, 9],
  [15, 7, 13, 5],
];
export const BG_ROWS = 17;

/** Continuous light level (fog + zone darkness) of the floor or ceiling seen at pixel row y (bob 0). */
export function rowLevel(y: number, amb: number): number {
  const F = k('F256') / 256;
  const dy = Math.abs(y + 0.5 - k('HORIZON'));
  const q = (F / (2 * dy)) * 4; // floor distance in quarter cells
  const near = k('FOG_NEAR_Q');
  const fog = Math.max(0, (q - near) / k('FOG_STEP_Q') + 0.5);
  return Math.min(7, fog + amb);
}

/**
 * tiles[zone][row] = 64 colour indices (row-major 8 x 8). The light level of each screen row (0..7) picks a
 * position along the zone's floor or ceiling ramp (near -> far); the fraction between two ramp colours is
 * Bayer-dithered.
 */
export function bgTiles(): number[][][] {
  return ZONES.map((z) =>
    Array.from({ length: BG_ROWS }, (_, r) => {
      const px: number[] = [];
      for (let ty = 0; ty < 8; ty++) {
        const y = r * 8 - 8 + ty;
        const ramp = y < k('HORIZON') ? z.ceil : z.floor;
        const pos = (rowLevel(y, z.amb) / 7) * (ramp.length - 1);
        const lo = Math.floor(pos);
        const frac = pos - lo;
        for (let tx = 0; tx < 8; tx++) {
          const i = Math.min(ramp.length - 1, frac > (BAYER[ty & 3]![tx & 3]! + 0.5) / 16 ? lo + 1 : lo);
          px.push(ramp[i]!);
        }
      }
      return px;
    }),
  );
}

export function bgAsm(): string {
  const tiles = bgTiles();
  const tileBytes = (px: number[]) => Array.from({ length: 32 }, (_, i) => (px[i * 2]! << 4) | px[i * 2 + 1]!);
  return [
    '; GENERATED by games/nadir/tools/bg.ts from DESIGN.md §3.5, §3.7 - do not edit.',
    `BG_ROWS = ${BG_ROWS}`,
    `BG_ZONE_BYTES = ${BG_ROWS * 32}`,
    `BG_BYTES = ${BG_ROWS * 32 * tiles.length}`,
    '',
    '.data',
    '; the background map: 16 columns x 17 rows, row r uses tile r + 1 (tile 0 is never drawn)',
    'bg_map:',
    ...Array.from({ length: BG_ROWS }, (_, r) => `    .fill 16, ${r + 1}`),
    '',
    '; seam colours per zone: near (the floor ramp\'s third step) and far (its fourth)',
    'seam_tab:',
    ...byteLines(ZONES.map((z) => z.floor[Math.min(2, z.floor.length - 1)]!)),
    'seam_far:',
    ...byteLines(ZONES.map((z) => z.floor[Math.min(3, z.floor.length - 1)]!)),
    '; light pools per zone: core colour and rim colour',
    '; ellipse profile: 256 * sqrt(1 - (i / 32)^2), i = 0..32',
    'ellipse_tab:',
    ...byteLines(Array.from({ length: 33 }, (_, i) => Math.min(255, Math.round(256 * Math.sqrt(1 - (i / 32) ** 2))))),
    'pool_core:',
    ...byteLines(ZONES.map((z) => z.light)),
    'pool_rim:',
    ...byteLines(ZONES.map((z) => z.rim)),
    '.xdata',
    '; copied to bgram by init: per zone 17 tiles (4 bits per pixel, colour 0 transparent)',
    'bg_x:',
    ...tiles.flatMap((zone, zi) => [`    ; zone ${zi} ${ZONES[zi]!.name}`, ...zone.flatMap((t) => byteLines(tileBytes(t), 16))]),
    '',
  ].join('\n');
}

if (isMain(import.meta.url)) {
  writeFileSync(join(GAME_DIR, 'bg.gen.asm'), bgAsm());
  console.log('bg.gen.asm written');
}
