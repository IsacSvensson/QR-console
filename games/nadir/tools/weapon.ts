// NADIR - the weapon art (DESIGN.md §6.1): art/weapon.txt -> weapon.gen.asm. Every part is cut into 8 x 8 tiles
// (4 bits per pixel, colour 0 transparent, as SPR and MAP draw them); equal tiles are stored once, tile 0 is the
// empty one (MAP skips it). Per part: its map (tile numbers, row by row) and its size in tiles.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { GAME_DIR, byteLines } from './util';

export interface Part {
  name: string;
  w: number;
  h: number;
  /** palette index 1..15, 0 = transparent, [y][x] */
  px: number[][];
}

export function readWeapon(file = join(GAME_DIR, 'art', 'weapon.txt')): Part[] {
  const lines = readFileSync(file, 'utf8').split(/\r?\n/);
  const legend = new Map<string, number>();
  const parts: Part[] = [];
  for (let i = 0; i < lines.length; i++) {
    const t = lines[i]!.trim().split(/\s+/);
    const where = `art/weapon.txt:${i + 1}`;
    if (t[0] === 'legend')
      for (let k = 1; k + 1 < t.length; k += 2) {
        const v = t[k + 1] === 't' ? 0 : parseInt(t[k + 1]!, 10);
        if (!(v >= 0 && v < 16)) throw new Error(`${where}: colour ${t[k + 1]}`);
        if (v === 0 && t[k + 1] !== 't') throw new Error(`${where}: colour 0 is transparent in MAP; use 't'`);
        legend.set(t[k]!, v);
      }
    else if (t[0] === 'part') {
      const p: Part = { name: t[1]!, w: Number(t[2]), h: Number(t[3]), px: [] };
      if (p.w % 8 || p.h % 8 || p.w > 64 || p.h > 64) throw new Error(`${where}: a part is a multiple of 8 px, at most 64 x 64`);
      parts.push(p);
    } else if (t[0] === 'rows') {
      const p = parts[parts.length - 1]!;
      for (i++; lines[i]!.trim() !== 'end'; i++) {
        const row = [...lines[i]!.trim()].map((ch) => {
          const v = legend.get(ch);
          if (v === undefined) throw new Error(`art/weapon.txt:${i + 1}: '${ch}' is not in the legend`);
          return v;
        });
        if (row.length !== p.w) throw new Error(`art/weapon.txt:${i + 1}: ${row.length} pixels, part ${p.name} is ${p.w} wide`);
        p.px.push(row);
      }
      if (p.px.length !== p.h) throw new Error(`part ${p.name}: ${p.px.length} rows, expected ${p.h}`);
    }
  }
  return parts;
}

/** 32 bytes per tile: rows of 4 bytes, the left pixel in the high nibble */
export function tileBytes(p: Part, tx: number, ty: number): number[] {
  const out: number[] = [];
  for (let y = 0; y < 8; y++) for (let x = 0; x < 8; x += 2) out.push((p.px[ty * 8 + y]![tx * 8 + x]! << 4) | p.px[ty * 8 + y]![tx * 8 + x + 1]!);
  return out;
}

export function weaponTiles(parts = readWeapon()) {
  const tiles: number[][] = [new Array<number>(32).fill(0)];
  const key = new Map<string, number>([[tiles[0]!.join(','), 0]]);
  const maps = parts.map((p) => {
    const m: number[] = [];
    for (let ty = 0; ty < p.h / 8; ty++)
      for (let tx = 0; tx < p.w / 8; tx++) {
        const b = tileBytes(p, tx, ty);
        const k = b.join(',');
        let n = key.get(k);
        if (n === undefined) {
          n = tiles.length;
          tiles.push(b);
          key.set(k, n);
        }
        m.push(n);
      }
    return { part: p, map: m };
  });
  if (tiles.length > 256) throw new Error(`weapon: ${tiles.length} tiles (a map byte holds 256)`);
  return { tiles, maps };
}

export function weaponAsm(parts = readWeapon()): string {
  const { tiles, maps } = weaponTiles(parts);
  return [
    '; GENERATED by games/nadir/tools/weapon.ts from art/weapon.txt - do not edit.',
    ...maps.flatMap(({ part }) => [`WPN_${part.name.toUpperCase()}_W = ${part.w / 8}`, `WPN_${part.name.toUpperCase()}_H = ${part.h / 8}`]),
    `WPN_TILES = ${tiles.length}`,
    '',
    '.data',
    '; per part: tile numbers row by row (0 = empty)',
    ...maps.flatMap(({ part, map }) => [`wpn_${part.name}:`, ...byteLines(map, 16)]),
    '; 8 x 8 tiles, 4 bits per pixel, colour 0 transparent: in xdata, copied to RAM by init (DESIGN §9 cut list)',
    `.var wpn_tiles, ${tiles.length * 32}`,
    '.xdata',
    'wpn_tiles_x:',
    ...tiles.flatMap((t) => byteLines(t, 16)),
    '.code',
    '',
  ].join('\n');
}
