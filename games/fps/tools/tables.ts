// Writes ../tables.gen.asm for the FPS spike (SPIKE.md §2–3): trig and reciprocal tables, the per-ray camera
// and column tables for 32/64/128 rays, the wall textures, the map, the wall-column run lists (xdata, packed)
// and the enemy at every screen size (xdata, packed). Run: npx tsx games/fps/tools/tables.ts (npm run fps:gen).
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DARK, ENEMY, FLASH, GUN, SPRITE_SIZES, TEXTURES, TEXTURE_OF, pixels, readLevel } from './art';
import { GAME_DIR, isMain } from './util';

// ---- numbers shared with the engine (SPIKE.md §3) ----------------------------------------------------
export const ANGLES = 1024; // a full turn
export const ONE = 256; // 8.8 fixed point: one cell, or a unit vector
export const FOCAL = 97; // pixels per unit at depth 1: 64 / tan(FOV / 2), FOV = 2 * atan(0.66)
export const PLANE = 169; // camera plane half width, 0.66 in 8.8
export const VIEW_W = 128;
export const VIEW_H = 96;
export const PERP_MIN = 64; // the nearest a wall is drawn (a quarter cell)
export const HMAX = Math.floor((FOCAL * ONE) / PERP_MIN); // 388
export const RECIP_N = 512;
export const RECIP_MAX = 32767; // 128 cells; components below 2/256 are handled apart (SPIKE.md §3.3)
export const RAY_COUNTS = [32, 64, 128];
export const SPRITE_SCALE = 0.75; // enemy height / wall height at the same depth

/** Rays across the view for `n` rays: the camera-plane position of ray c, in 1.7 fixed point. */
export const camOf = (n: number, c: number) => Math.round(((2 * c + 1) / n - 1) * 128);

/** SPIKE.md §3.4: the rows of a wall column of height h and the texel row of each. */
export function wallRows(h: number): { y0: number; runs: [number, number][] } {
  const runs: [number, number][] = [];
  let y0 = -1;
  for (let y = 0; y < VIEW_H; y++) {
    const s = 16 * y + 8 - (16 * (VIEW_H / 2) - 8 * h); // sixteenths of a pixel below the wall's top
    if (s < 0 || s >= 16 * h) continue;
    if (y0 < 0) y0 = y;
    const k = Math.min(15, Math.floor(s / h));
    const last = runs[runs.length - 1];
    if (last && last[0] === k) last[1]++;
    else runs.push([k, 1]);
  }
  return { y0, runs };
}

/** Index into SPRITE_SIZES for an enemy at wall height h (nearest size; 255 = too small to draw). */
export function spriteSizeFor(h: number): number {
  const want = SPRITE_SCALE * h;
  if (want < 4) return 255;
  let best = 0;
  for (let i = 1; i < SPRITE_SIZES.length; i++) if (Math.abs(SPRITE_SIZES[i]! - want) < Math.abs(SPRITE_SIZES[best]! - want)) best = i;
  return best;
}

const words = (label: string, v: (string | number)[], per = 16) => {
  const out = [`${label}:`];
  for (let i = 0; i < v.length; i += per) out.push(`    .word ${v.slice(i, i + per).join(', ')}`);
  return out.join('\n');
};
const bytes = (label: string, v: number[], per = 32, dir = '.byte') => {
  const out = label ? [`${label}:`] : [];
  for (let i = 0; i < v.length; i += per) out.push(`    ${dir} ${v.slice(i, i + per).join(', ')}`);
  return out.join('\n');
};

/** 4bpp 8x8 tiles of a picture (w x h pixels, multiples of 8), in column-major or row-major tile order. */
export function tilesOf(px: number[], w: number, h: number, order: 'cols' | 'rows'): number[] {
  const out: number[] = [];
  const tw = w / 8;
  const th = h / 8;
  const tile = (tx: number, ty: number) => {
    for (let y = 0; y < 8; y++)
      for (let x = 0; x < 8; x += 2) out.push((px[(ty * 8 + y) * w + tx * 8 + x]! << 4) | px[(ty * 8 + y) * w + tx * 8 + x + 1]!);
  };
  if (order === 'cols') for (let tx = 0; tx < tw; tx++) for (let ty = 0; ty < th; ty++) tile(tx, ty);
  else for (let ty = 0; ty < th; ty++) for (let tx = 0; tx < tw; tx++) tile(tx, ty);
  return out;
}

/** The enemy picture `pose` scaled to s x s pixels by nearest neighbour. */
export function scaledEnemy(pose: string, s: number): number[] {
  const src = pixels(ENEMY[pose]!, 16, 16);
  const out: number[] = [];
  for (let y = 0; y < s; y++) for (let x = 0; x < s; x++) out.push(src[Math.floor((y * 16) / s) * 16 + Math.floor((x * 16) / s)]!);
  return out;
}

export const TEX_NAMES = Object.keys(TEXTURES);
export const POSES = Object.keys(ENEMY);

export function generateTables(): string {
  const level = readLevel();
  const L: string[] = [
    '; generated by games/fps/tools/tables.ts (npm run fps:gen) - do not edit',
    `HMAX = ${HMAX}`,
    `PERP_MIN = ${PERP_MIN}`,
    `FOCAL = ${FOCAL}`,
    `FOCAL256 = ${FOCAL * ONE}`,
    `PLANE = ${PLANE}`,
    `RECIP_N = ${RECIP_N}`,
    `VIEW_H = ${VIEW_H}`,
    `START_X = ${level.player.x * ONE + ONE / 2}`,
    `START_Y = ${level.player.y * ONE + ONE / 2}`,
    `ENEMY_X = ${level.enemy.x * ONE + ONE / 2}`,
    `ENEMY_Y = ${level.enemy.y * ONE + ONE / 2}`,
    `NUM_SIZES = ${SPRITE_SIZES.length}`,
  ];

  // run lists: per h, [y0, count, (texel, rows) * count], unpacked to runs_ram at init
  const runBytes: number[] = [];
  const runIdx: string[] = ['runs_ram'];
  for (let h = 1; h <= HMAX; h++) {
    runIdx.push(`runs_ram + ${runBytes.length}`);
    const { y0, runs } = wallRows(h);
    runBytes.push(y0, runs.length, ...runs.flat());
  }
  // enemy sprites: per pose, per size, column-major tiles, unpacked to spr_ram at init
  const sprBytes: number[] = [];
  const sprTable: string[] = [];
  for (const pose of POSES) {
    for (const s of SPRITE_SIZES) {
      sprTable.push(`spr_ram + ${sprBytes.length} - 32`, String(s / 8));
      sprBytes.push(...tilesOf(scaledEnemy(pose, s), s, s, 'cols'));
    }
  }
  L.push(`RUNS_BYTES = ${runBytes.length}`, `SPR_BYTES = ${sprBytes.length}`, '', '.data');

  const sin = Array.from({ length: ANGLES + ANGLES / 4 }, (_, i) => Math.round(Math.sin((2 * Math.PI * i) / ANGLES) * ONE));
  L.push('; sin of angle i (1024 = full turn) in 8.8; cos(a) = sin_t[a + 256]', words('sin_t', sin));
  const recip = Array.from({ length: RECIP_N }, (_, i) => (i === 0 ? RECIP_MAX : Math.min(RECIP_MAX, Math.round((ONE * ONE) / i))));
  L.push('; |1 / x| in 8.8 for an 8.8 ray component x = 0..511, capped at 128 cells', words('recip_t', recip));
  for (const n of RAY_COUNTS) {
    const w = VIEW_W / n; // pixels per ray
    L.push(`; ${n} rays: camera-plane position (1.7) and RAM buffer address of the ray's first row`);
    L.push(words(`cam_${n}`, Array.from({ length: n }, (_, c) => camOf(n, c))));
    L.push(
      words(
        `colb_${n}`,
        Array.from({ length: n }, (_, c) => {
          const bx = (c * w) >> 1; // byte column (two pixels per byte)
          return `buf + ${(bx >> 2) * 384 + (bx & 3)}`;
        }),
        8,
      ),
    );
  }
  // MAP of the view: tile (tx, ty) is buffer tile tx * 12 + ty, so a pixel column is linear in the buffer
  const view: number[] = [];
  for (let ty = 0; ty < VIEW_H / 8; ty++) for (let tx = 0; tx < 16; tx++) view.push(1 + tx * (VIEW_H / 8) + ty);
  L.push('; the view as a 16x12 tilemap over the RAM buffer (tiles = buf - 32)', bytes('view_map', view, 16));
  L.push('; the level, 16x16 cells, copied to RAM at init', bytes('level_map', level.cells, 16));

  // textures: column-major, one byte per texel holding the colour twice (a two-pixel-wide column)
  const texLabel = (name: string, dark: number) => `tex_${name}_${dark}`;
  for (const name of TEX_NAMES) {
    const px = pixels(TEXTURES[name]!, 16, 16);
    if (px.includes(0)) throw new Error(`texture ${name} uses colour 0 (not drawn by MAP)`);
    for (const dark of [0, 1]) {
      const col: number[] = [];
      for (let u = 0; u < 16; u++) for (let v = 0; v < 16; v++) {
        const c = dark ? DARK[px[v * 16 + u]!]! : px[v * 16 + u]!;
        col.push(c * 17);
      }
      L.push(bytes(texLabel(name, dark), col, 16));
    }
  }
  const texTable: string[] = [];
  for (let code = 0; code < 10; code++) {
    const t = TEXTURE_OF[code];
    texTable.push(t ? texLabel(t, 0) : '0', t ? texLabel(t, 1) : '0');
  }
  L.push('; texture of each map code: x side, y side', words('tex_table', texTable, 4));
  L.push('; run list address for each wall height h = 0..HMAX (RAM)', words('run_idx', runIdx, 8));
  L.push('; enemy sprite size index for each wall height (255 = too small)', bytes('spr_size', Array.from({ length: HMAX + 1 }, (_, h) => (h === 0 ? 255 : spriteSizeFor(h)))));
  L.push(`; per pose (${POSES.join(', ')}), per size (${SPRITE_SIZES.join(', ')}): tiles base, tiles per side`, words('spr_table', sprTable, 4));
  L.push(`size_px: .word ${SPRITE_SIZES.join(', ')}`);
  L.push('seq_map: .byte 1, 2, 3, 4, 5, 6, 7, 8');
  L.push('gun_map: .byte 1, 2, 3, 4, 5, 6', 'gun_tiles = gun_data - 32', bytes('gun_data', tilesOf(pixels(GUN, 24, 16), 24, 16, 'rows')));
  L.push('flash_tiles = flash_data - 32', bytes('flash_data', tilesOf(pixels(FLASH, 24, 8), 24, 8, 'rows')));

  L.push('', '.xdata', 'runs_x:', '.pack', bytes('', runBytes), '.endpack', 'spr_x:', '.pack', bytes('', sprBytes), '.endpack', '');
  return L.join('\n');
}

/**
 * The unrolled column writer for rays `w` pixels wide (SPIKE.md §3.5): one store per row of the view, then RET.
 * Calling `duff_end - k * entry` with r1 = (first row address) - 384 writes the last k rows.
 */
export function generateDuff(w: number): string {
  const L = [`; generated by games/fps/tools/tables.ts (npm run fps:gen) - do not edit`, `; ${VIEW_H} rows, rays ${w} pixel(s) wide`, 'duff:'];
  for (let i = 0; i < VIEW_H; i++) {
    const a = `[r1 + ${4 * i}]`;
    if (w === 1) L.push(`    LDB r7, ${a}`, '    AND r7, r5', '    OR r7, r6', `    STB ${a}, r7`);
    else L.push(`    ${w === 2 ? 'STB' : 'ST'} ${a}, r6`);
  }
  L.push('duff_end:', '    RET', '');
  return L.join('\n');
}

export const GENERATED: Record<string, () => string> = {
  'tables.gen.asm': generateTables,
  'duff1.gen.asm': () => generateDuff(1),
  'duff2.gen.asm': () => generateDuff(2),
  'duff4.gen.asm': () => generateDuff(4),
};

if (isMain(import.meta.url)) {
  for (const [file, gen] of Object.entries(GENERATED)) {
    const out = gen();
    writeFileSync(join(GAME_DIR, file), out);
    console.log(`${file}: ${out.length} chars`);
  }
}
