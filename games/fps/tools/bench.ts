// npm run bench:fps — measures the FPS spike (PLAN.md M26, SPIKE.md §5) and writes bench/fps.md:
//  1. the cost of one whole image for rays 1, 2 and 4 pixels wide (each built to render a whole image per frame,
//     run without a cycle limit on the inputs of every recorded replay);
//  2. where the cycles go (2-pixel rays), by the routine executing each instruction;
//  3. the shipped build: cycles per frame, images per second, ROM, RAM, cartridge and QR size.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DEFAULT_QR, blockSizeFor, defaultFrameCount } from '@qrc/qr';
import { blockCount } from '@qrc/transport';
import { expandInputs, type ReplayFile } from '@qrc/vm';
import { type FpsBuild, buildFps, configText, startVM } from './game';
import { GAME_DIR } from './util';

const REPLAYS = ['spin', 'door_fight', 'hall', 'hurt'];
const BUDGET = 50_000;
const HALF = 25_000; // the per-frame ceiling the replays assert (half the budget, as in Part 3)
const REPO = join(GAME_DIR, '../..');

const inputsOf = (name: string) => {
  const rf = JSON.parse(readFileSync(join(GAME_DIR, 'replays', `${name}.json`), 'utf8')) as ReplayFile & { frames: number };
  return { seed: rf.seed ?? 1, inputs: expandInputs(rf.inputs, rf.frames) };
};

interface Run {
  frames: number;
  images: number;
  max: number;
  sum: number;
  imageMax: number;
  imageSum: number;
}

/** Runs every replay's inputs; per frame and per image (an image = the frames from one snapshot to its present). */
function measure(b: FpsBuild, cyclesPerFrame: number, onStep?: (b: FpsBuild) => void): Run {
  const run: Run = { frames: 0, images: 0, max: 0, sum: 0, imageMax: 0, imageSum: 0 };
  for (const name of REPLAYS) {
    const { seed, inputs } = inputsOf(name);
    const vm = startVM(b, seed, cyclesPerFrame);
    let acc = 0;
    for (let f = 0; f < inputs.length; f++) {
      const images = vm.read16(b.sym('images'));
      vm.step(inputs[f]!);
      onStep?.(b);
      if (vm.fault) throw new Error(`${name}: ${vm.fault}`);
      const c = vm.cyclesLastFrame;
      run.frames++;
      run.max = Math.max(run.max, c);
      run.sum += c;
      acc += c;
      if (vm.read16(b.sym('images')) !== images) {
        run.images++;
        run.imageMax = Math.max(run.imageMax, acc);
        run.imageSum += acc;
        acc = 0;
      }
    }
    if (vm.overruns) throw new Error(`${name}: ${vm.overruns} overruns`);
  }
  return run;
}

/** Instruction cycles (SYS counted as 8, block syscalls' per-byte cost not included) per routine group. */
async function breakdown() {
  const b = await buildFps(configText(2, 64));
  const labels = [...b.asm.symbols.entries()].filter(([n, v]) => /^[a-z]\w*$/.test(n) && v < b.cart.sections.code.length).sort((x, y) => x[1] - y[1]);
  const group = (n: string) =>
    ['col_draw', 'duff', 'duff_end'].includes(n) ? 'wall columns (run lists, unrolled stores)' : ['cast', 'tiny_side'].includes(n) ? 'rays (set-up, DDA, hit, texture column)' : ['present', 'enemy_draw', 'gun_draw', 'hud_draw', 'fmul'].includes(n) ? 'present (MAP, enemy, gun, status bar)' : ['render_step', 'snapshot'].includes(n) ? 'image set-up' : 'game logic (player, doors, enemy)';
  const of = new Map<number, string>();
  for (let pc = 0, i = 0; pc < b.cart.sections.code.length; pc += 4) {
    while (i + 1 < labels.length && labels[i + 1]![1] <= pc) i++;
    of.set(pc, group(labels[i]![0]));
  }
  const counts = new Map<string, number>();
  let images = 0;
  for (const name of REPLAYS) {
    const { seed, inputs } = inputsOf(name);
    const vm = startVM(b, seed, 10_000_000);
    vm.tracer = (pc) => {
      const g = of.get(pc) ?? '?';
      counts.set(g, (counts.get(g) ?? 0) + (vm.read8(pc) === 0x20 ? 8 : 1));
    };
    for (const i of inputs) vm.step(i);
    images += vm.read16(b.sym('images'));
  }
  return { counts, images };
}

const pct = (a: number, b: number) => `${((100 * a) / b).toFixed(0)} %`;
const k = (v: number) => v.toLocaleString('en-US').replace(/,/g, ' ');

const out: string[] = [
  '# FPS spike benchmark (M26)',
  '',
  '_Generated by `npm run bench:fps` (games/fps/tools/bench.ts). Measured in the headless VM on the inputs of the four',
  `recorded replays (${REPLAYS.join(', ')}). Cycles are the VM's own count (1 per instruction, 8 per syscall + the ISA 2`,
  'per-byte cost); nothing here is a real-device measurement._',
  '',
  '## 1. One whole image, by ray width',
  '',
  'Each variant is built to render a whole image in one frame and run without a cycle limit. An image includes the',
  "frame's game logic. *Frames per image* is how many frames an image needs if no frame may exceed",
  `${k(HALF)} cycles (the replays' ceiling) or the hard budget of ${k(BUDGET)}.`,
  '',
  '| Ray width | Rays | Max cycles / image | Mean | Frames per image at 25 000 (images/s) | at 50 000 (images/s) | ROM |',
  '|---|---:|---:|---:|---:|---:|---:|',
];
const variants: Record<number, Run> = {};
for (const w of [1, 2, 4] as const) {
  const n = 128 / w;
  const b = await buildFps(configText(w, n));
  const r = measure(b, 10_000_000);
  variants[w] = r;
  const at = (cap: number) => {
    const fpi = Math.ceil(r.imageMax / cap);
    return `${fpi} (${(60 / fpi).toFixed(0)})`;
  };
  const s = b.cart.sections;
  out.push(`| ${w} px | ${n} | ${k(r.imageMax)} | ${k(Math.round(r.imageSum / r.images))} | ${at(HALF)} | ${at(BUDGET)} | ${k(s.code.length + s.rodata.length + s.sound.length)} B |`);
  console.log(`${w} px: max ${r.imageMax}, mean ${Math.round(r.imageSum / r.images)} cycles per image`);
}

const { counts, images } = await breakdown();
const total = [...counts.values()].reduce((a, c) => a + c, 0);
out.push('', '## 2. Where the cycles go (2-pixel rays, whole image per frame)', '', `Per image, mean over ${k(images)} images (SYS counted as 8; the per-byte cost of FILL/COPY not included).`, '', '| Part | Cycles / image | Share |', '|---|---:|---:|');
for (const [g, c] of [...counts.entries()].sort((a, b2) => b2[1] - a[1])) out.push(`| ${g} | ${k(Math.round(c / images))} | ${pct(c, total)} |`);

const shipped = await buildFps();
const r = measure(shipped, BUDGET);
const s = shipped.cart.sections;
const rom = s.code.length + s.rodata.length + s.sound.length;
const ramEnd = shipped.sym('spr_ram') + shipped.sym('SPR_BYTES');
const K = blockCount(shipped.bytes.length, blockSizeFor(DEFAULT_QR.version, DEFAULT_QR.ecc));
out.push(
  '',
  `## 3. The shipped build (${shipped.sym('COLW')}-pixel rays, ${shipped.sym('RAY_CHUNK')} rays per frame)`,
  '',
  '| Metric | Value |',
  '|---|---|',
  `| Cycles per frame | max ${k(r.max)}, mean ${k(Math.round(r.sum / r.frames))} (budget ${k(BUDGET)}; 0 overruns) |`,
  `| Images per second | ${((60 * r.images) / r.frames).toFixed(1)} (one image every ${(r.frames / r.images).toFixed(2)} frames) |`,
  `| Cycles per image | max ${k(r.imageMax)}, mean ${k(Math.round(r.imageSum / r.images))} |`,
  `| ROM | ${k(rom)} B of 32 768 (code ${k(s.code.length)}, data ${k(s.rodata.length)}, sound ${s.sound.length}) |`,
  `| xdata | ${k(s.xdata?.length ?? 0)} B packed (run lists ${k(shipped.sym('RUNS_BYTES'))} B, enemy sprites ${k(shipped.sym('SPR_BYTES'))} B unpacked into RAM) |`,
  `| RAM | ${k(ramEnd - 0x8000)} B of 32 768 used by variables (view buffer 6 144 B) |`,
  `| Cartridge | ${k(shipped.bytes.length)} B (ISA ${shipped.cart.header.isaVersion}) |`,
  `| As QR (v${DEFAULT_QR.version}-${DEFAULT_QR.ecc}, 150 ms) | K = ${K} blocks, ${defaultFrameCount(K)} frames per loop (${((defaultFrameCount(K) * 150) / 1000).toFixed(1)} s) |`,
  '',
);
writeFileSync(join(REPO, 'bench/fps.md'), out.join('\n'));
console.log(out.join('\n'));
