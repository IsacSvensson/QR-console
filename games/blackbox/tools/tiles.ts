  DESK: ['........', '44444444', '49999994', '49999994', '49999994', '44444444', '4......4', '........'],
  DOOR: ['q......q', 'q......q', 'q......q', 'q......q', 'q......q', 'q......q', 'q......q', 'q......q'],
  LOCKED: ['qqqqqqqq', 'q666666q', 'q6.66.6q', 'q666666q', 'q66ee66q', 'q666666q', 'q666666q', 'qqqqqqqq'],
  VENT: ['qqqqqqqq', 'q3r3r3rq', 'q3r3r3rq', 'q3r3r3rq', 'q3r3r3rq', 'q3r3r3rq', 'q3r3r3rq', 'qqqqqqqq'],
