// Generates ../tiles.gen.asm: one tileset per zone group, drawn once with symbolic colours
// (p main, q dark, r light, s accent, t accent 2) and recoloured per tileset. Also the tile attribute table.
// Run: npx tsx games/blackbox/tools/tiles.ts
import { writeFileSync } from 'node:fs';
import { TILE_NAMES } from './gen';

// order = tile codes 1..12 (code 0 = floor is never drawn; the floor is the CLS colour)
